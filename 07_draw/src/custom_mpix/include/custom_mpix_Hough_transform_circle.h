#ifndef CUSTOM_MPIX_HOUGH_TRANSFORM_CIRCLE_H_
#define CUSTOM_MPIX_HOUGH_TRANSFORM_CIRCLE_H_

#include <stdint.h>
#include <stddef.h>

/* ---------------------------------------------------------------------------------------------
 *                    Порт преобразования Хафа для окружностей (Arduino IDE -> Zephyr)
 *
 * База — ваш computeHoughCircle()/getDotsFromHoughSpace() из houghTransformCircle.h
 * (брут-форс: для каждого контурного пикселя в пространство Хафа "штампуется" вся
 * окружность радиуса R; после — поиск и слияние пиков голосования).
 *
 * Отличия от оригинала:
 *   1. Работает напрямую по RGB24 (яркость считается "на лету", как в custom_mpix_convolution.c),
 *      отдельный ч/б буфер входа не нужен.
 *   2. Область поиска (ROI) — обязательный параметр конфигурации, а не весь кадр: так
 *      исключаются шум по краям кадра и текст/оверлеи, нанесённые поверх изображения.
 *   3. Окружность в пространство Хафа "штампуется" целочисленным алгоритмом Брезенхэма
 *      (midpoint circle, 8-way symmetry) вместо sin()/cos() на каждый из 360 градусов —
 *      без float, без дублирующихся точек контура. Смещения контура кэшируются между
 *      вызовами, пока радиус не меняется (а он у вас фиксированный).
 *   4. Голосующая точка клиппится ПОТОЧЕЧНО по границам ROI (в оригинале при выходе
 *      окружности за границы кадра терялся голос СРАЗУ ВЕСЬ, целиком).
 *   5. Восстановление (x, y) центра по индексу в getDotsFromHoughSpace() в оригинале
 *      перепутано местами (x и y после раскрытия индекса не совпадают с тем, как этот
 *      индекс заполнялся при голосовании) — здесь пересчитано верно.
 *   6. Аккумулятор — uint16_t, а не uint8_t (в оригинале мог переполниться и "обнулиться"
 *      при большом количестве наложившихся голосов).
 *   7. Слияние близких пиков сравнивает КВАДРАТ евклидова расстояния (без sqrt()), и
 *      усредняет координаты с весом по числу голосов, а не просто пополам.
 *   8. Никакого malloc/free: аккумулятор, кэш смещений контура и буфер "сырых" кандидатов
 *      на слияние — статические буферы в PSRAM (.ext_ram.bss), как и остальные кадровые
 *      буферы проекта. Результат пишется в массив, который выделяет вызывающая сторона.
 * --------------------------------------------------------------------------------------------- */

/* Максимальная площадь ROI (в пикселях), под которую рассчитан статический аккумулятор.
 * По умолчанию — площадь всего кадра этого проекта (160x120): ROI всегда является
 * подмножеством кадра, поэтому большего и не требуется. Если кадр в вашем проекте больше —
 * переопределите этот макрос ДО подключения заголовка. */
#ifndef CUSTOM_MPIX_HOUGH_ACCUM_MAX_PIXELS
#define CUSTOM_MPIX_HOUGH_ACCUM_MAX_PIXELS (160 * 120)
#endif

/* Максимальный поддерживаемый радиус окружности — ограничивает размер статического кэша
 * смещений контура окружности (см. п.3 выше). */
#ifndef CUSTOM_MPIX_HOUGH_MAX_RADIUS
#define CUSTOM_MPIX_HOUGH_MAX_RADIUS 64
#endif

/* Максимальное число "сырых" пиков голосования, обрабатываемых за один вызов ДО слияния
 * (не то же самое, что max_circles в конфиге ниже — это внутренний технический лимит,
 * на практике почти всегда намного больше реального числа пиков на кадр). */
#ifndef CUSTOM_MPIX_HOUGH_MAX_RAW_CANDIDATES
#define CUSTOM_MPIX_HOUGH_MAX_RAW_CANDIDATES 128
#endif

/* Область поиска (Region Of Interest). Границы полуоткрытые: x принадлежит [x_min, x_max),
 * y принадлежит [y_min, y_max) — как обычные C-циклы for(x = x_min; x < x_max; x++). */
struct custom_mpix_roi {
	int32_t x_min;
	int32_t y_min;
	int32_t x_max;
	int32_t y_max;
};

/* Конфигурация одного вызова поиска окружностей. */
struct custom_mpix_hough_circle_config {
	/* Область кадра, в которой ищем (см. custom_mpix_roi). */
	struct custom_mpix_roi roi;
	/* Искомый радиус окружности (фиксированный, известен заранее). */
	int32_t radius;
	/* Порог яркости: пиксель ярче этого значения считается точкой контура
	 * (аналог "buf_img[iter] > 200" в оригинале). */
	uint8_t edge_threshold;
	/* Порог голосов в пространстве Хафа: пик ярче этого значения считается
	 * кандидатом в центр окружности (аналог "threshold = 120" в оригинале). */
	uint16_t vote_threshold;
	/* Порог расстояния (в пикселях) для слияния двух кандидатов в один
	 * (аналог "distEuclidian < 20" в оригинале; сравнивается квадрат расстояния,
	 * поэтому здесь тоже задаётся обычное, не возведённое в квадрат, значение). */
	int32_t merge_dist;
	/* Сколько окружностей максимум записать в out_circles (вызывающая сторона
	 * обязана выделить массив как минимум такого размера). Аналог жёсткого
	 * лимита "arr_X[50]" в оригинале, но настраиваемый. */
	uint32_t max_circles;
};

/* Одна найденная окружность. */
struct custom_mpix_circle {
	int32_t x;
	int32_t y;
	int32_t radius;
	uint16_t votes;
};

/** Найти окружности заданного радиуса в области ROI кадра RGB24 методом Хафа.
 *
 * buf_rgb24   - кадр в формате RGB24, размер width*height*3 байт.
 * width, height - размеры ВСЕГО кадра (ROI внутри cfg должен в них помещаться).
 * cfg         - конфигурация поиска (ROI, радиус, пороги) — см. выше.
 * out_circles - массив под результат, вызывающая сторона обязана выделить
 *               не менее cfg->max_circles элементов.
 * out_count   - сюда пишется реальное число найденных окружностей (0..cfg->max_circles).
 *
 * Возвращает 0 при успехе, отрицательный errno-код при некорректных аргументах
 * (NULL-указатель, ROI вне кадра, radius <= 0 или больше CUSTOM_MPIX_HOUGH_MAX_RADIUS,
 * площадь ROI больше CUSTOM_MPIX_HOUGH_ACCUM_MAX_PIXELS).
 */
int custom_mpix_hough_circle_detect(const uint8_t *buf_rgb24, int width, int height,
				     const struct custom_mpix_hough_circle_config *cfg,
				     struct custom_mpix_circle *out_circles, uint32_t *out_count);

#endif /* CUSTOM_MPIX_HOUGH_TRANSFORM_CIRCLE_H_ */
