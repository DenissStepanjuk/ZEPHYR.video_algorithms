#ifndef THREAD_UI_H_
#define THREAD_UI_H_

#include <zephyr/kernel.h>

/*
 * Всё, что связано со слайдерами, интерфейсом LVGL и потоком, который
 * этим занимается, реализовано в ui_thread.c. Здесь - только то, что
 * должно быть видно снаружи (в main.c), чтобы там можно было создать
 * и запустить этот поток через k_thread_create().
 */

// Размер стека UI-потока. LVGL (разбор шрифтов, флекс-раскладка, обработка
// touch-событий) требует заметно больше стека, чем обычный поток "по
// умолчанию" - если раньше вся эта логика уже стабильно работала в main()
// с CONFIG_MAIN_STACK_SIZE из prj.conf, возьмите то же значение здесь.
// Если стек окажется маленьким, будет либо жёсткий крэш/reset, либо (при
// включённом CONFIG_STACK_SENTINEL/CONFIG_THREAD_STACK_INFO) понятная
// ошибка "stack overflow" в логе - в этом случае просто увеличьте это число.
#define UI_THREAD_STACK_SIZE 8192

// Приоритет UI-потока. Положительное число = вытесняемый (preemptible)
// поток; чем меньше число, тем выше приоритет. 5 - средний приоритет,
// достаточный, чтобы UI не "подвисал", но не мешающий более критичным
// системным потокам (например, будущим потокам с датчиками/связью).
#define UI_THREAD_PRIORITY 5

// Стек потока физически выделен (K_THREAD_STACK_DEFINE) в ui_thread.c.
// K_THREAD_STACK_DECLARE даёт этому же символу внешнюю (extern) видимость
// здесь, чтобы main.c мог передать его в k_thread_create().
K_THREAD_STACK_DECLARE(ui_thread_stack, UI_THREAD_STACK_SIZE);

// Структура данных потока тоже определена в ui_thread.c - main.c получает
// на неё указатель через объявление extern.
extern struct k_thread ui_thread_data;


/*
 * Точка входа UI-потока: инициализация дисплея, построение интерфейса
 * (слайдеры), главный цикл LVGL (обработка touch-событий и вывод значений
 * слайдеров в терминал). Реализация - в ui_thread.c, регистрируется в
 * main() через k_thread_create().
 */
void ui_thread_entry(void *arg1, void *arg2, void *arg3);

#endif /* THREAD_UI_H_ */
