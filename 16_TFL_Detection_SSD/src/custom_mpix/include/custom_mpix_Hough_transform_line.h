#ifndef CUSTOM_MPIX_HOUGH_TRANSFORM_LINE_H_
#define CUSTOM_MPIX_HOUGH_TRANSFORM_LINE_H_

#include <stdint.h>
#include <stddef.h>

/* struct custom_mpix_roi объявлена в custom_mpix_Hough_transform_circle.h — переиспользуем
 * её здесь, а не дублируем тип с тем же именем (иначе main.c, подключающий оба заголовка,
 * не соберётся из-за повторного определения struct custom_mpix_roi). Если вы используете
 * этот модуль отдельно от Хафа для окружностей — просто оставьте этот include, он лёгкий
 * (только объявления типов, без .c-зависимостей). */
#include "custom_mpix_Hough_transform_circle.h"

/* ---------------------------------------------------------------------------------------------
 *                     Порт преобразования Хафа для линий (Arduino IDE -> Zephyr)
 *
 * База — ваш computeHoughLine()/getDotsFromHoughSpace() из houghTransformLine.h: для каждого
 * контурного пикселя голосуем по всем углам theta в пространство (theta, R), затем подавляем
 * "размазанные" по оси R пики и извлекаем параметры найденных линий.
 *
 * Отличия от оригинала (важно, часть — исправление реальных багов):
 *   1. БАГ ОРИГИНАЛА: cos()/sin() в оригинале вызывались от T в ГРАДУСАХ напрямую, хотя
 *      принимают РАДИАНЫ ("R = x*cos(T) + y*sin(T)" с T от -90 до 90 градусов, без
 *      перевода в радианы) — пространство Хафа заполнялось не гладкой синусоидой, а
 *      фактически алиасированным шумом. Здесь угол переводится в радианы явно при
 *      построении таблицы cos/sin (см. custom_mpix_hough_line_build_theta_table()).
 *   2. БАГ ОРИГИНАЛА: "uint8_t arr_R[50]" — R может достигать диагонали кадра (для 160x120
 *      это ~400), что переполняет uint8_t (макс. 255). Здесь R хранится как int32_t.
 *   3. БАГ ОРИГИНАЛА: слияние соседних "горячих" точек в getDotsFromHoughSpace() читает
 *      buf_hough[i + dotLen] без проверки границы буфера — потенциальный выход за пределы
 *      массива на правом краю пространства Хафа. Здесь границы проверяются явно.
 *   4. "int arr_lines[6][238]" в оригинале хранит целый профиль y(x) для каждой линии,
 *      жёстко под высоту кадра 238px из другого проекта. Здесь линия хранится компактно
 *      как параметры (theta, R) — см. struct custom_mpix_line; для отрисовки координаты
 *      двух конечных точек считаются функцией custom_mpix_hough_line_to_segment() и
 *      передаются в уже готовый custom_mpix_draw_line().
 *   5. Похожие линии сливаются по разнице (theta, R) напрямую (O(1) на пару), а не через
 *      усреднённое евклидово расстояние между полными профилями y(x) (O(width) на пару,
 *      как в оригинальном drawFiltredLines()).
 *   6. Работает напрямую по RGB24 (яркость "на лету", как и в остальных custom_mpix_*
 *      модулях), ROI — обязательный параметр, а не весь кадр (та же причина, что и в
 *      Хафе для окружностей: шум по краям, оверлеи поверх кадра).
 *   7. Никакого malloc/free: пространство Хафа, таблица cos/sin и буфер "сырых" кандидатов
 *      на слияние — статические буферы в PSRAM (.ext_ram.bss), как и везде в проекте.
 * --------------------------------------------------------------------------------------------- */

/* Максимальная "диагональ" (ширина одной строки пространства Хафа, т.е. диапазон R,
 * умноженный на 2 — см. комментарий про смещение diagonal/2 в custom_mpix_Hough_transform_line.c),
 * под которую рассчитан статический аккумулятор. По умолчанию — под ROI не больше полного
 * кадра 160x120 этого проекта: 2*ceil(sqrt(160^2+120^2)) = 400. Переопределите ДО подключения
 * заголовка, если у вас кадр/ROI больше. */
#ifndef CUSTOM_MPIX_HOUGH_LINE_ACCUM_MAX_DIAGONAL
#define CUSTOM_MPIX_HOUGH_LINE_ACCUM_MAX_DIAGONAL 400
#endif

/* Максимальное число углов theta в таблице — соответствует шагу 1° на полном диапазоне
 * -90..90 включительно (181 значение). Если возьмёте больший шаг (cfg->theta_step_deg > 1),
 * реально используемых углов будет меньше, но буфер рассчитан на самый мелкий шаг. */
#ifndef CUSTOM_MPIX_HOUGH_LINE_MAX_THETA_COUNT
#define CUSTOM_MPIX_HOUGH_LINE_MAX_THETA_COUNT 181
#endif

/* Максимальное число "сырых" пиков голосования, обрабатываемых за один вызов ДО слияния. */
#ifndef CUSTOM_MPIX_HOUGH_LINE_MAX_RAW_CANDIDATES
#define CUSTOM_MPIX_HOUGH_LINE_MAX_RAW_CANDIDATES 256
#endif

/* Конфигурация одного вызова поиска линий. */
struct custom_mpix_hough_line_config {
	/* Область кадра, в которой ищем (см. custom_mpix_roi в custom_mpix_Hough_transform_circle.h). */
	struct custom_mpix_roi roi;
	/* Порог яркости: пиксель ярче этого значения считается точкой контура. */
	uint8_t edge_threshold;
	/* Порог голосов в пространстве Хафа: пик ярче этого значения считается кандидатом
	 * в параметры линии (аналог "threshold = 60" в оригинале). */
	uint16_t vote_threshold;
	/* Шаг угла theta в градусах (в оригинале жёстко 1°). Меньше — точнее и медленнее,
	 * больше — грубее и быстрее. Должен быть > 0 и делить диапазон 180° на не более
	 * чем CUSTOM_MPIX_HOUGH_LINE_MAX_THETA_COUNT шагов. */
	int32_t theta_step_deg;
	/* Порог разницы по theta (в градусах) для слияния двух кандидатов в одну линию. */
	int32_t merge_theta_deg;
	/* Порог разницы по R (в пикселях) для слияния двух кандидатов в одну линию
	 * (аналог "distEuclidian < 30" в оригинале, но сравниваются напрямую параметры,
	 * а не профиль y(x) — см. п.5 в шапке файла). */
	int32_t merge_r;
	/* Сколько линий максимум записать в out_lines (вызывающая сторона обязана выделить
	 * массив как минимум такого размера). Аналог лимита "arr_lines[6][...]" в оригинале,
	 * но настраиваемый. */
	uint32_t max_lines;
};

/* Одна найденная линия в нормальной форме (theta, R): x*cos(theta) + y*sin(theta) = r,
 * theta в градусах в диапазоне [-90, 90]. */
struct custom_mpix_line {
	int32_t theta_deg;
	int32_t r;
	uint16_t votes;
};

/** Найти прямые линии в области ROI кадра RGB24 методом Хафа.
 *
 * buf_rgb24   - кадр в формате RGB24, размер width*height*3 байт.
 * width, height - размеры ВСЕГО кадра (ROI внутри cfg должен в них помещаться).
 * cfg         - конфигурация поиска (ROI, шаг угла, пороги) — см. выше.
 * out_lines   - массив под результат, вызывающая сторона обязана выделить
 *               не менее cfg->max_lines элементов.
 * out_count   - сюда пишется реальное число найденных линий (0..cfg->max_lines).
 *
 * Возвращает 0 при успехе, отрицательный errno-код при некорректных аргументах.
 */
int custom_mpix_hough_line_detect(const uint8_t *buf_rgb24, int width, int height,
				   const struct custom_mpix_hough_line_config *cfg,
				   struct custom_mpix_line *out_lines, uint32_t *out_count);

/** Превратить параметры (theta, R) найденной линии в отрезок [x0,y0]-[x1,y1],
 * пересекающий границы roi (для последующей передачи в custom_mpix_draw_line()).
 *
 * line - линия, полученная из custom_mpix_hough_line_detect().
 * roi  - область, в границах которой нужен отрезок (обычно то же ROI, что и при поиске).
 * x0,y0,x1,y1 - куда записать координаты концов отрезка.
 *
 * Возвращает 0 при успехе, -EINVAL при некорректных аргументах (NULL, вырожденный ROI,
 * или line->theta_deg вне диапазона [-90, 90]).
 */
int custom_mpix_hough_line_to_segment(const struct custom_mpix_line *line,
				       const struct custom_mpix_roi *roi,
				       int32_t *x0, int32_t *y0, int32_t *x1, int32_t *y1);

#endif /* CUSTOM_MPIX_HOUGH_TRANSFORM_LINE_H_ */
