#ifndef CUSTOM_MPIX_HSV_H_
#define CUSTOM_MPIX_HSV_H_

#include <stdint.h>
#include <stddef.h>

/* ---------------------------------------------------------------------------------------------
 *                        Порт HSV-маски (Arduino IDE -> Zephyr)
 *
 * База — ваш jpeg2HSV()/applyMask() из colorMask.h: перевод RGB в HSV и проверка каждого
 * пикселя на попадание в заданный диапазон (Hue/Saturation/Value).
 *
 * Отличия от оригинала:
 *   1. Никакого отдельного buf_hsv-буфера и malloc: HSV пикселя считается "на лету" прямо
 *      внутри одного прохода по buf_rgb24, сравнивается с порогами и сразу же либо не
 *      трогает исходные R,G,B, либо перезаписывает их в белый (255,255,255) — по вашему
 *      явному требованию "для экономии места".
 *   2. БАГ ОРИГИНАЛА: в jpeg2HSV() при delta < 0.00001 (чёрный/серый пиксель, r=g=b) или
 *      max == 0 код делает "continue" ДО записи buf_hsv[i..i+2] — эти байты остаются
 *      мусором из ps_malloc() (он не зануляет память), а не реальным HSV. Здесь такие
 *      пиксели явно получают h=0, s=0, v=max — без пропуска записи.
 *   3. Целочисленная арифметика вместо double — на MCU быстрее, единообразно с остальными
 *      custom_mpix_* модулями (custom_mpix_convolution.c и т.д. тоже без float в горячем цикле).
 *   4. H, S, V все в диапазоне 0..255 (H масштабируется из честных 0..360 градусов, как и
 *      в оригинале), удобно для слайдеров — как и требовалось.
 *   5. Диапазон включительный с обеих сторон (>=min && <=max), а не строгий < / > как в
 *      оригинальном applyMask() — так hue_min=0/hue_max=255 действительно покрывает весь
 *      диапазон, а не исключает крайние значения.
 * --------------------------------------------------------------------------------------------- */

/* Смещения байт R/G/B внутри пикселя MPIX_FMT_RGB24 — согласовано с остальными custom_mpix_*
 * модулями, проверьте по факту на своём кадре, если цвета "не сходятся". */
#define CUSTOM_MPIX_RGB24_R_OFFSET 0
#define CUSTOM_MPIX_RGB24_G_OFFSET 1
#define CUSTOM_MPIX_RGB24_B_OFFSET 2

/* Пороговый диапазон HSV-маски. Все поля 0..255, границы включительные.
 * Значения по умолчанию для "пропускать всё" — hue_min=0, hue_max=255, аналогично sat/val. */
struct custom_mpix_hsv_range {
	uint8_t hue_min;
	uint8_t hue_max;
	uint8_t sat_min;
	uint8_t sat_max;
	uint8_t val_min;
	uint8_t val_max;
};

/** Перевести один пиксель RGB24 в HSV (все компоненты 0..255).
 *
 * Публичная функция — пригодится, если понадобится HSV одного пикселя отдельно от маски
 * (например, для отладки/показа значения под курсором на вебстраничке).
 *
 * r, g, b - компоненты входного пикселя.
 * h, s, v - куда записать результат (0..255 каждый). Указатели не должны быть NULL.
 */
void custom_mpix_rgb_to_hsv(uint8_t r, uint8_t g, uint8_t b, uint8_t *h, uint8_t *s, uint8_t *v);

/** Применить HSV-маску ко всему кадру RGB24 "на лету", in-place, без malloc.
 * Пиксель, чей HSV попадает в диапазон range (включительно по всем трём каналам),
 * остаётся неизменным. Пиксель вне диапазона перекрашивается в белый (255,255,255).
 *
 * buf_rgb24   - кадр в формате RGB24, размер width*height*3 байт, изменяется на месте.
 * width, height - размеры кадра.
 * range       - пороговый диапазон HSV.
 *
 * Возвращает 0 при успехе, -EINVAL при некорректных аргументах (NULL-указатель,
 * width/height <= 0, либо min > max в одном из каналов диапазона).
 */
int custom_mpix_hsv_mask(uint8_t *buf_rgb24, int width, int height,
			  const struct custom_mpix_hsv_range *range);

#endif /* CUSTOM_MPIX_HSV_H_ */
