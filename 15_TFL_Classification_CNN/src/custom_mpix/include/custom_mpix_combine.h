#ifndef CUSTOM_MPIX_COMBINE_H_
#define CUSTOM_MPIX_COMBINE_H_

#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>

/* ---------------------------------------------------------------------------------------------
 *                     Порт объединения изображений (Arduino IDE -> Zephyr)
 *
 * База — ваш insertLogo() из combination.h: вставить одно изображение (логотип) поверх
 * другого (основной кадр) по заданным координатам левого верхнего угла.
 *
 * Отличия от оригинала:
 *   1. НИКАКОГО JPEG внутри модуля. В этой версии libmpix есть только mpix_image_jpeg_encode()
 *      (RGB24 -> JPEG), декодера JPEG (JPEG -> RGB24) нет вообще (проверено по исходникам:
 *      src/ содержит только op_jpeg_encode.c). Оригинал декодировал ОБЕ картинки из JPEG на
 *      каждый вызов — это было нужно только потому, что у ESP32-камеры кадры и так были в
 *      JPEG. У вас основной кадр уже в RGB24 (декодировать не нужно), а логотип (esp32.jpg)
 *      декодируется ОДИН РАЗ заранее, офлайн, на этапе сборки — не на каждый кадр на плате
 *      (см. соответствующий скрипт и инструкцию по generate_inc_file_for_target()). Поэтому
 *      этот модуль работает только с уже готовым RGB24 с обеих сторон.
 *   2. БАГ ОРИГИНАЛА: проверка границ "x + width < width_img + 1" — не пускает вставку ровно
 *      по правому/нижнему краю кадра (off-by-one). Здесь "x + width <= width_img".
 *   3. БАГ ОРИГИНАЛА: отрицательные x/y не отсекались — "x_real = (x - 1) * 3" при x=0 уходит
 *      в отрицательный индекс буфера (UB). Здесь x >= 0 и y >= 0 проверяются явно.
 *   4. Единый порядок байт R,G,B (CUSTOM_MPIX_RGB24_R/G/B_OFFSET), как и во всех остальных
 *      custom_mpix_* модулях, вместо перепутанных +2,+1,+0 из оригинала (там это был побочный
 *      эффект конкретного порядка байт, который отдавал fmt2rgb888 на ESP32).
 *   5. Никакого malloc/free: оба буфера (приёмник и источник) уже существуют — приёмник
 *      обычно buf_frame_4_processing (статический, PSRAM), источник — встроенный в прошивку
 *      const-массив логотипа (flash). Функция только копирует пиксели между ними.
 *   6. ДОБАВЛЕНО (по вашему запросу): флаг прозрачной вставки по цветовому ключу
 *      (chroma key) — пиксели логотипа, точно совпадающие с заданным цветом, не
 *      перезаписывают кадр, вместо этого сквозь них виден исходный кадр. В оригинале
 *      вставка всегда была сплошным прямоугольником без прозрачности.
 * --------------------------------------------------------------------------------------------- */

/* Смещения байт R/G/B внутри пикселя MPIX_FMT_RGB24 — согласовано с остальными custom_mpix_*
 * модулями, проверьте по факту на своём кадре, если цвета "не сходятся". */
#define CUSTOM_MPIX_RGB24_R_OFFSET 0
#define CUSTOM_MPIX_RGB24_G_OFFSET 1
#define CUSTOM_MPIX_RGB24_B_OFFSET 2

/* Настройки одной вставки. */
struct custom_mpix_combine_config {
	/* Если true — пиксели логотипа, точно равные (chroma_key_r, chroma_key_g, chroma_key_b),
	 * не копируются в приёмник (сквозь них остаётся исходное содержимое кадра). Если false —
	 * вставка сплошная, как в оригинале (chroma_key_* при этом не используются). */
	bool use_chroma_key;
	uint8_t chroma_key_r;
	uint8_t chroma_key_g;
	uint8_t chroma_key_b;
};

/** Вставить изображение (логотип) поверх другого изображения (основного кадра), оба в RGB24.
 *
 * buf_base_rgb24            - приёмник (основной кадр), размер base_width*base_height*3 байт,
 *                              изменяется на месте.
 * base_width, base_height   - размеры основного кадра.
 * buf_logo_rgb24            - источник (логотип), размер logo_width*logo_height*3 байт,
 *                              не изменяется (может быть в const/flash-памяти).
 * logo_width, logo_height   - размеры логотипа.
 * x, y                      - координаты левого верхнего угла вставки в системе координат
 *                              основного кадра.
 * config                    - настройки прозрачности; NULL означает сплошную вставку без
 *                              прозрачности (эквивалент {.use_chroma_key = false}).
 *
 * Возвращает 0 при успехе, -EINVAL при некорректных аргументах (NULL-указатель,
 * base_width/height или logo_width/height <= 0, x < 0, y < 0, либо логотип с этими
 * координатами выходит за пределы основного кадра).
 */
int custom_mpix_combine_insert_rgb24(uint8_t *buf_base_rgb24, int base_width, int base_height,
				      const uint8_t *buf_logo_rgb24, int logo_width, int logo_height,
				      int x, int y,
				      const struct custom_mpix_combine_config *config);

#endif /* CUSTOM_MPIX_COMBINE_H_ */
